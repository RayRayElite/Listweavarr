/* Optional read-only pairing. Only artwork and opaque target IDs are fetched;
 * cached images and playback bookmarks continue working with the server off. */
(function (root) {
  'use strict';
  function pairing(value) {
    const data = typeof value === 'string' ? JSON.parse(value) : value;
    const url = new URL(data.url);
    if (
      !['http:', 'https:'].includes(url.protocol) ||
      url.username ||
      url.password ||
      url.search ||
      url.hash ||
      url.pathname !== '/' ||
      !/^[\w-]{32,100}$/.test(data.token || '')
    )
      throw new Error('Paste the artwork pairing generated by Listweavarr Settings.');
    if (data.progressToken && !/^[\w-]{32,100}$/.test(data.progressToken))
      throw new Error('Invalid progress pairing.');
    return {
      url: url.origin,
      token: data.token,
      ...(data.progressToken ? { progressToken: data.progressToken, serverId: data.serverId } : {}),
    };
  }
  function targetFromHref(href) {
    try {
      const value = decodeURIComponent(decodeURIComponent(href));
      const machine = value.match(
        /\/server\/([^/?#]+)\/(?:provider\/[^/]+\/)?playlist(?:[?#]|$|\/)/
      )?.[1];
      const playlist = value.match(/(?:key=|\/)playlists\/(\d+)(?:[&#/?]|$)/)?.[1];
      return machine && playlist ? machine + '/' + playlist : null;
    } catch {
      return null;
    }
  }
  function create(core, storage, fetcher = root.fetch?.bind(root), cache) {
    let database;
    if (!cache) {
      function db() {
        return (database ||= new Promise((resolve, reject) => {
          const request = indexedDB.open('listweavarr-playlist-posters', 1);
          request.onupgradeneeded = () => request.result.createObjectStore('posters');
          request.onsuccess = () => resolve(request.result);
          request.onerror = () => reject(new Error('Local artwork storage is unavailable.'));
        }));
      }
      cache = {
        async access(key, value) {
          const dbValue = await db();
          return new Promise((resolve, reject) => {
            const transaction = dbValue.transaction('posters', value ? 'readwrite' : 'readonly');
            const store = transaction.objectStore('posters');
            const request = value ? store.put(value, key) : store.get(key);
            transaction.oncomplete = () => resolve(value || request.result);
            transaction.onerror = transaction.onabort = () =>
              reject(new Error('Could not cache artwork.'));
          });
        },
      };
    }
    const key = 'playlist-companion:artwork-pairing';
    let lastSync = 0,
      busy = false;
    async function record(scope) {
      const value = await cache.access(core.storageKey(scope));
      // Old versions stored a raw Blob; preserve those user-picked posters.
      return value instanceof Blob ? { blob: value, source: 'local' } : value;
    }
    async function get(scope) {
      return (await record(scope))?.blob || null;
    }
    async function set(scope, blob, source = 'local', revision = '') {
      if (
        !(blob instanceof Blob) ||
        !/^image\/(jpeg|png|webp|gif)$/.test(blob.type) ||
        blob.size > 8_000_000
      )
        throw new Error('Choose a supported image under 8 MB.');
      await cache.access(core.storageKey(scope), { blob, source, revision });
    }
    function connect(value) {
      const data = pairing(value);
      storage.setItem(key, JSON.stringify(data));
      lastSync = 0;
    }
    function disconnect() {
      storage.removeItem(key);
      lastSync = 0;
    }
    async function sync(api, force = false) {
      const raw = storage.getItem(key);
      if (!raw || busy || (!force && Date.now() - lastSync < 300000)) return { updated: 0 };
      busy = true;
      try {
        const cfg = pairing(raw);
        const options = {
          headers: { Authorization: 'Bearer ' + cfg.token },
          credentials: 'omit',
          signal: AbortSignal.timeout(12000),
          cache: 'no-store',
        };
        const endpoint = cfg.url + '/api/playlist-companion/artwork';
        const response = await fetcher(endpoint, options);
        if (!response.ok) throw new Error('Artwork pairing is unavailable or revoked.');
        const data = await response.json();
        if (data.schema !== 1 || !Array.isArray(data.items) || data.items.length > 1000)
          throw new Error('Unsupported artwork catalogue.');
        const selections = await api.playlists();
        let updated = 0;
        for (const row of data.items) {
          const scope = selections.find(
            (value) => value.serverId === row.serverId && value.playlistId === row.playlistId
          );
          if (!scope || typeof row.revision !== 'string') continue;
          const saved = await record(scope);
          if (saved?.source === 'local' || saved?.revision === row.revision) continue;
          const query = new URLSearchParams({ serverId: row.serverId, playlistId: row.playlistId });
          const image = await fetcher(endpoint + '?' + query, {
            ...options,
            signal: AbortSignal.timeout(12000),
          });
          if (!image.ok) continue;
          await set(scope, await image.blob(), 'listweavarr', row.revision);
          updated++;
        }
        lastSync = Date.now();
        if (updated) root.dispatchEvent?.(new Event('listweavarr-playlist-progress'));
        return { updated };
      } finally {
        busy = false;
      }
    }
    function mount(api) {
      const urls = new Map(),
        edited = new Map();
      let disposed = false,
        timer,
        refreshing = false;
      function restore(element, original) {
        if (original.kind === 'src') {
          element.setAttribute('src', original.value || '');
          if (original.srcset) element.setAttribute('srcset', original.srcset);
        } else element.style.backgroundImage = original.value;
      }
      function paint() {
        for (const anchor of document.querySelectorAll('a[href]')) {
          const id = targetFromHref(anchor.getAttribute('href'));
          const url = urls.get(id)?.url;
          if (!url) continue;
          const element =
            anchor.querySelector('img') || anchor.querySelector('[style*="background-image"]');
          if (!element) continue;
          if (!edited.has(element))
            edited.set(
              element,
              element.tagName === 'IMG'
                ? {
                    kind: 'src',
                    value: element.getAttribute('src'),
                    srcset: element.getAttribute('srcset'),
                  }
                : { kind: 'background', value: element.style.backgroundImage }
            );
          if (element.tagName === 'IMG') {
            if (element.getAttribute('src') !== url) {
              element.removeAttribute('srcset');
              element.setAttribute('src', url);
            }
          } else if (element.style.backgroundImage !== `url("${url}")`)
            element.style.backgroundImage = `url("${url}")`;
        }
        for (const [element] of edited) if (!element.isConnected) edited.delete(element);
      }
      async function refresh() {
        if (disposed || refreshing) return;
        refreshing = true;
        try {
          const selections = await api.playlists();
          const active = new Set();
          for (const scope of selections) {
            const blob = await get(scope);
            if (!blob) continue;
            const id = scope.serverId + '/' + scope.playlistId;
            active.add(id);
            if (urls.get(id)?.blob !== blob) {
              if (urls.has(id)) URL.revokeObjectURL(urls.get(id).url);
              urls.set(id, { blob, url: URL.createObjectURL(blob) });
            }
          }
          for (const [id, value] of urls)
            if (!active.has(id)) {
              URL.revokeObjectURL(value.url);
              urls.delete(id);
            }
          if (!disposed) paint();
        } catch {
          /* Keep cached/native artwork when the server is offline. */
        } finally {
          refreshing = false;
        }
      }
      const schedule = () => {
        if (!timer)
          timer = setTimeout(() => {
            timer = null;
            paint();
          }, 100);
      };
      const observer = new MutationObserver(schedule);
      observer.observe(document.getElementById('plex') || document.body, {
        childList: true,
        subtree: true,
        attributes: true,
        attributeFilter: ['src', 'href', 'style'],
      });
      root.addEventListener('hashchange', refresh);
      root.addEventListener('listweavarr-playlist-progress', refresh);
      refresh();
      return () => {
        disposed = true;
        observer.disconnect();
        clearTimeout(timer);
        root.removeEventListener('hashchange', refresh);
        root.removeEventListener('listweavarr-playlist-progress', refresh);
        for (const [element, original] of edited) restore(element, original);
        for (const value of urls.values()) URL.revokeObjectURL(value.url);
      };
    }
    return {
      get,
      set,
      connect,
      disconnect,
      sync,
      mount,
      paired: () => !!storage.getItem(key),
      close: () => {
        if (database) database.then((value) => value.close()).catch(() => {});
      },
    };
  }
  if (typeof module !== 'undefined' && module.exports)
    module.exports = { pairing, create, targetFromHref };
  else root.ListweavarrPlaylistArtwork = create(root.ListweavarrPlaylistCore, localStorage);
})(globalThis);
